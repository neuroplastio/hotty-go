func TestReplaceSection(t *testing.T) {
	ok := "a <!-- docgen:packages -->old<!-- /docgen:packages --> b"
	got, err := replaceSection([]byte(ok), packagesStart, packagesEnd, "new\n")
	if err != nil || string(got) != "a <!-- docgen:packages -->\nnew\n<!-- /docgen:packages --> b" {
		t.Errorf("%q, %v", got, err)
	}
	for name, src := range map[string]string{
		"no start":  "<!-- /docgen:packages -->",
		"no end":    "<!-- docgen:packages -->",
		"reversed":  "<!-- /docgen:packages --><!-- docgen:packages -->",
		"twice":     ok + ok,
		"no marker": "plain",
	} {
		if _, err := replaceSection([]byte(src), packagesStart, packagesEnd, "x"); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
}

// copyDir copies a directory tree.
func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		out := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(out, 0o755)
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(out, b, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

func TestChangesAndWrite(t *testing.T) {
	root := t.TempDir()
	copyDir(t, fixture, root)
	_, files := generate(t, root)
	changes, err := Changes(root, files)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, c := range changes {
		got = append(got, c.String())
	}
	want := "changed README.md, new docs/api/README.md, new docs/api/fix.md, new docs/api/sub.md"
	if strings.Join(got, ", ") != want {
		t.Errorf("changes: %v", got)
	}
	if err := Write(root, files, changes); err != nil {
		t.Fatal(err)
	}
	// Written, nothing is left to change; a page no package has is removed.
	if err := os.WriteFile(filepath.Join(root, "docs/api/gone.md"), []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, files = generate(t, root)
	changes, err = Changes(root, files)
	if err != nil {
		t.Fatal(err)
	}
	if len(changes) != 1 || changes[0].String() != "removed docs/api/gone.md" {
		t.Fatalf("after writing: %v", changes)
	}
	if err := Write(root, files, changes); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(root, "docs/api/gone.md")); !os.IsNotExist(err) {
		t.Error("the stale page is still there")
	}
}

