var (
	anchorRE = regexp.MustCompile(`<a id="([^"]+)"></a>`)
	linkRE   = regexp.MustCompile(`\]\(([^)\s]+)\)`)
	// codeRE is code, fenced or a span, whose brackets are not links: an
	// Example's Markdown in a Go string.
	codeRE = regexp.MustCompile("(?s)```.*?```|`[^`\n]*`")
)

// Every link the documentation makes inside the repository leads to a file
// that is there, and to an anchor on it.
func TestLinksResolve(t *testing.T) {
	for _, root := range []string{fixture, "../.."} {
		_, files := generate(t, root)
		anchors := map[string]map[string]bool{}
		for p, b := range files {
			anchors[p] = map[string]bool{}
			for _, m := range anchorRE.FindAllStringSubmatch(string(b), -1) {
				anchors[p][m[1]] = true
			}
		}
		for p, b := range files {
			for _, m := range linkRE.FindAllStringSubmatch(codeRE.ReplaceAllString(string(b), ""), -1) {
				target := m[1]
				if strings.Contains(target, "://") {
					continue
				}
				file, frag, _ := strings.Cut(target, "#")
				if file == "" {
					file = p
				} else {
					file = filepath.ToSlash(filepath.Join(filepath.Dir(p), file))
				}
				if _, ok := files[file]; !ok {
					if _, err := os.Stat(filepath.Join(root, file)); err != nil {
						t.Errorf("%s: %s: %s is not there", root, p, target)
					}
					continue
				}
				if frag != "" && !anchors[file][frag] {
					t.Errorf("%s: %s: no anchor for %s", root, p, target)
				}
			}
		}
	}
}
