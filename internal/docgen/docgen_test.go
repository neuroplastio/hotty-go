const fixture = "testdata/fixture"

func generate(t *testing.T, root string) (*Module, map[string][]byte) {
	t.Helper()
	m, err := Load(root)
	if err != nil {
		t.Fatal(err)
	}
	files, err := m.Generate()
	if err != nil {
		t.Fatal(err)
	}
	return m, files
}

func keys(files map[string][]byte) []string {
	var out []string
	for k := range files {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func TestPackagesFound(t *testing.T) {
	m, files := generate(t, fixture)
	if m.Path != "example.com/fix" {
		t.Errorf("module path %q", m.Path)
	}
	// Internal packages and commands have no page; the root comes first.
	// (Large is documented by its group's comment.)
	want := []string{"README.md", "docs/api/README.md", "docs/api/fix.md", "docs/api/sub.md"}
	if got := keys(files); strings.Join(got, " ") != strings.Join(want, " ") {
		t.Errorf("files %v, want %v", got, want)
	}
	if m.Packages[0].Rel != "" || m.Packages[1].ImportPath != "example.com/fix/sub" {
		t.Errorf("order: %s, %s", m.Packages[0].ImportPath, m.Packages[1].ImportPath)
	}
}

